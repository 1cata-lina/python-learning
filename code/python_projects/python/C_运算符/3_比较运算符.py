'''
1.比较运算符用于比较两个值，结果是布尔值：True 或 False。
2.运算符列表
• >
• <
• >=
• <=
• ==
• !=
'''
print(2>3)
print(3>2)
print(2==3)
print(10!=5)
# 一瓶矿泉水售价 2 元，可乐 3 元：矿泉水价格＞可乐价格（2 > 3）
print(2>3)
# 小明身高 135cm，班级标准入校身高最低 130cm：小明身高≥入校标准（135 >= 130）
print(135>=130)
# 公交车限载 40 人，现在车上一共 42 人：现有人数≤限载人数（42 <= 40）
print(42<=40)
# 一斤苹果 8 元，一斤橘子 8 元：苹果单价 == 橘子单价（8 == 8）
print(8 == 8)
# 一支铅笔 1 元，橡皮 2 元：铅笔价格！= 橡皮价格（1 != 2）
print(1!=2)
# 书包承重上限 5kg，书本总重 6kg：书本重量＜书包承重（6 < 5）
print(6<5)
# 考试及格线 60 分，小红刚好考 60 分：分数≥及格线（60 >= 60）
print(60>=60)
# 泳池水深 1.8 米，小亮身高 1.7 米：小亮身高＞水深（1.7 > 1.8）
print(1.7>1.8)
# 一箱牛奶 24 盒，两箱合计 48 盒：2×24 == 48
print(2*24==48)
# 打车起步里程 3km，实际行驶 4km：行驶里程！= 起步里程（4 != 3）
print(4!=3)